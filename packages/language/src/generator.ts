import { defaultComponentRegistry, type ComponentRegistry } from '@webrad/component-registry';
import { parseForm, type ComponentNode, type FormModel } from '@webrad/project-model';

export interface GenerateFormOptions {
  readonly registry?: ComponentRegistry;
  readonly runtimeModule?: string;
  readonly generatedSuffix?: string;
}

export interface GeneratedFormArtifacts {
  readonly generatedFileName: string;
  readonly declarationFileName: string;
  readonly userFileName: string;
  readonly source: string;
  readonly typings: string;
  readonly userSource: string;
}

export class LanguageGenerationError extends Error {
  public constructor(message: string) {
    super(message);
    this.name = 'LanguageGenerationError';
  }
}

function generatedClassName(form: FormModel, suffix: string): string {
  return `${form.name}${suffix}`;
}

function runtimeTypes(form: FormModel): readonly string[] {
  return [...new Set(['WebForm', ...form.components.map((component) => component.type)])].sort();
}

function assignedEvents(form: FormModel): readonly {
  readonly component: ComponentNode;
  readonly eventName: string;
  readonly handlerName: string;
}[] {
  return form.components.flatMap((component) =>
    Object.entries(component.events).flatMap(([eventName, handlerName]) =>
      handlerName === null ? [] : [{ component, eventName, handlerName }],
    ),
  );
}

function assertKnownComponentTypes(form: FormModel, registry: ComponentRegistry): void {
  for (const component of form.components) {
    if (!registry.has(component.type)) {
      throw new LanguageGenerationError(
        `Cannot generate ${form.name}: component type "${component.type}" is not registered.`,
      );
    }
  }
}

function quoted(value: string): string {
  return JSON.stringify(value);
}

function componentConstruction(component: ComponentNode, registry: ComponentRegistry): string {
  const definition = registry.require(component.type);
  if (definition.visual) {
    return `new ${component.type}(this.requireComponentElement(${quoted(component.id)}))`;
  }
  return `new ${component.type}(${JSON.stringify(component.props)})`;
}

export function generateFormSource(
  formInput: FormModel,
  options: GenerateFormOptions = {},
): string {
  const form = parseForm(formInput);
  const registry = options.registry ?? defaultComponentRegistry;
  assertKnownComponentTypes(form, registry);
  const runtimeModule = options.runtimeModule ?? '@webrad/runtime';
  const className = generatedClassName(form, options.generatedSuffix ?? 'Generated');
  const components = form.components.filter((component) => component.id !== form.rootComponentId);
  const events = assignedEvents(form);
  const lines: string[] = [
    '// Generated by WebRAD. Changes to this file will be replaced.',
    `import { ${runtimeTypes(form).join(', ')} } from ${quoted(runtimeModule)};`,
    '',
    `export abstract class ${className} extends WebForm {`,
  ];

  for (const component of components) {
    lines.push(`  public readonly ${component.name}: ${component.type};`);
  }
  if (components.length > 0) lines.push('');
  lines.push('  public constructor(element: HTMLElement) {', '    super(element);');
  for (const component of components) {
    lines.push(`    this.${component.name} = ${componentConstruction(component, registry)};`);
  }
  if (events.length > 0 && components.length > 0) lines.push('');
  for (const event of events) {
    const sender =
      event.component.id === form.rootComponentId ? 'this' : `this.${event.component.name}`;
    lines.push(
      `    this.bindGeneratedEvent(${sender}, ${quoted(event.eventName)}, ${quoted(event.handlerName)});`,
    );
  }
  lines.push('  }', '}', '');

  return `${lines.join('\n')}\n`;
}

export function generateFormTypings(
  formInput: FormModel,
  options: GenerateFormOptions = {},
): string {
  const form = parseForm(formInput);
  const registry = options.registry ?? defaultComponentRegistry;
  assertKnownComponentTypes(form, registry);
  const runtimeModule = options.runtimeModule ?? '@webrad/runtime';
  const className = generatedClassName(form, options.generatedSuffix ?? 'Generated');
  const components = form.components.filter((component) => component.id !== form.rootComponentId);
  const lines = [
    '// Generated by WebRAD for editor type information.',
    `import type { ${runtimeTypes(form).join(', ')} } from ${quoted(runtimeModule)};`,
    '',
    `export declare abstract class ${className} extends WebForm {`,
    ...components.map((component) => `  public readonly ${component.name}: ${component.type};`),
    '  public constructor(element: HTMLElement);',
    '}',
    '',
  ];
  return `${lines.join('\n')}\n`;
}

export function createUserFormSource(
  formInput: FormModel,
  options: Pick<GenerateFormOptions, 'generatedSuffix'> = {},
): string {
  const form = parseForm(formInput);
  const className = generatedClassName(form, options.generatedSuffix ?? 'Generated');
  const componentTypes = [...new Set(form.components.map((component) => component.type))].sort();
  const lines = [
    `import type { ${componentTypes.join(', ')} } from '@webrad/runtime';`,
    `import { ${className} } from './${form.name}.generated';`,
    '',
    `export class ${form.name} extends ${className} {`,
    '}',
    '',
  ];
  return lines.join('\n');
}

export function generateFormArtifacts(
  formInput: FormModel,
  options: GenerateFormOptions = {},
): GeneratedFormArtifacts {
  const form = parseForm(formInput);
  return {
    generatedFileName: `forms/${form.name}.generated.ts`,
    declarationFileName: `forms/${form.name}.generated.d.ts`,
    userFileName: `forms/${form.name}.ts`,
    source: generateFormSource(form, options),
    typings: generateFormTypings(form, options),
    userSource: createUserFormSource(form, options),
  };
}

export const generateFormDeclaration = generateFormTypings;
