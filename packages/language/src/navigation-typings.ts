import { pageClassName, type PageModel } from '@webrad/project-model';

export function pageParameterTypeName(page: PageModel): string {
  return `${pageClassName(page.name)}Parameters`;
}

export function pageParameterProperties(page: PageModel, input: boolean): readonly string[] {
  return (page.parameters ?? []).map((parameter) => {
    const optional = input
      ? !parameter.required || parameter.defaultValue !== undefined
      : !parameter.required && parameter.defaultValue === undefined;
    return `readonly ${JSON.stringify(parameter.name)}${optional ? '?' : ''}: ${parameter.type};`;
  });
}

/** One project-wide contract used by both the editor and the real compiler. */
export function generateNavigationTypings(pages: readonly PageModel[]): string {
  const destinations = new Map<string, string>();
  for (const page of pages) {
    const properties = pageParameterProperties(page, true);
    const value = properties.length
      ? `{ ${properties.join(' ')} }`
      : 'Readonly<Record<string, never>>';
    for (const destination of [page.name, page.id, '/' + page.name.toLowerCase()])
      destinations.set(destination, value);
  }
  return [
    '// Generated by WebRAD. Page navigation inputs are owned by the Project Model.',
    "import '@webrad/runtime';",
    "declare module '@webrad/runtime' {",
    '  interface WebRadPageParameters {',
    ...[...destinations].map(
      ([destination, value]) => `    ${JSON.stringify(destination)}: ${value};`,
    ),
    '  }',
    '}',
    '',
  ].join('\n');
}
